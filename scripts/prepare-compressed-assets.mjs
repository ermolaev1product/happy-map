// List exact existing public assets before the Worker build. Nothing in public/
// changes: Android and development continue to consume ordinary source assets.
import fs from 'node:fs';
import path from 'node:path';
const data=[],code=[];
const shared=new Set(['/en/vienna/places.json','/en/research/bars-2026-10-14/bar-registry.json','/en/research/bars-2026-10-14/bars.json','/en/paris/paris-data-derived.json']);
function visit(dir){for(const e of fs.readdirSync(dir,{withFileTypes:true})){
 const file=path.join(dir,e.name);if(e.isDirectory()){visit(file);continue;}
 const relative='/'+path.relative('public',file).split(path.sep).join('/');
 if(shared.has(relative))continue;
 const size=fs.statSync(file).size;
 if(file.endsWith('.json')&&size>50000)data.push(relative);
 if(/\.(?:js|css)$/.test(file)&&size>10000)code.push(relative);
}}
visit('public');data.sort();code.sort();
fs.writeFileSync('lib/generated-compressed-assets.mjs','// Generated by scripts/prepare-compressed-assets.mjs. Exact public asset allowlist.\nexport const additionalCompressedDataPaths = Object.freeze('+JSON.stringify(data,null,2)+');\nexport const compressedCodePaths = Object.freeze('+JSON.stringify(code,null,2)+');\n');
console.log('Prepared lossless asset storage:',data.length,'data assets and',code.length,'JS/CSS assets.');
